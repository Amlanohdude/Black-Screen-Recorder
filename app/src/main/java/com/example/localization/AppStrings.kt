fun AppStrings.getCoverName(presetId: CoverPresetId, fallbackName: String = ""): String {
    return when (presetId) {
        CoverPresetId.PURE_BLACK -> coverPureBlack
        CoverPresetId.CLOCK -> coverClock
        CoverPresetId.ANALOG_CLOCK -> coverAnalogClock
        CoverPresetId.LOCK_SCREEN -> coverLockStyle
        CoverPresetId.DIM_CLOCK -> coverDimClock
        CoverPresetId.SYSTEM_STATUS -> coverSystemStatus
        CoverPresetId.DASHCAM_HUD -> coverDashcamHud
        CoverPresetId.TIMER -> coverTimer
        CoverPresetId.MINIMAL -> coverMinimal
        CoverPresetId.CUSTOM -> fallbackName.ifEmpty { newCover }
    }
}

fun AppStrings.getPresetTitle(preset: RecordingPresetId): String = getPresetTitle(preset.name, preset.title)

fun AppStrings.getPresetTitle(presetId: String, fallbackName: String = ""): String {
    return when {
        presetId.contains("general", ignoreCase = true) -> presetGeneral
        presetId.contains("discreet", ignoreCase = true) -> presetDiscreetVideo
        presetId.contains("fps", ignoreCase = true) -> presetHighFps
        presetId.contains("lecture", ignoreCase = true) -> presetLectureMeeting
        presetId.contains("dictation", ignoreCase = true) -> presetDictation
        presetId.contains("music", ignoreCase = true) -> presetMusicAmbient
        else -> fallbackName.ifEmpty { presetGeneral }
    }
}

fun AppStrings.getStopBehavior(behavior: StopBehavior): String {
    return when (behavior) {
        StopBehavior.HOLD_TO_STOP -> holdToStop
        StopBehavior.TAP_TO_STOP -> tapToStop
        StopBehavior.CONFIRM_TO_STOP -> confirmToStop
    }
}

fun AppStrings.getGesture(gesture: ControlGesture): String {
    return when (gesture) {
        ControlGesture.SINGLE_TAP -> singleTap
        ControlGesture.DOUBLE_TAP -> doubleTap
        ControlGesture.LONG_PRESS -> longPress
    }
}

fun AppStrings.getMicLabel(mic: AudioMicSource): String {
    return when (mic) {
        AudioMicSource.PHONE_MIC -> micBuiltIn
        AudioMicSource.WIRED_HEADSET -> micWired
        AudioMicSource.BLUETOOTH_MIC -> micBluetooth
    }
}

fun AppStrings.formatAutoStopDuration(seconds: Int): String {
    if (seconds <= 0) return off
    val mins = seconds / 60
    return if (mins < 60) {
        "$mins $minutes"
    } else {
        val hrs = mins / 60
        val remMins = mins % 60
        if (remMins == 0) {
            if (hrs == 1) "1 $hour" else "$hrs $hours"
        } else {
            "$hrs $hour $remMins $minutes"
        }
    }
}

